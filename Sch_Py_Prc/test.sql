/*************************
Borderline Accounts
*************************/
WITH B_SA AS -- GET BORDERLINE SA
  (SELECT HIST.SA_ID,
    HIST.RS_CD
  FROM $$CCB_SCHEMA.CI_SA_RS_HIST HIST
  WHERE HIST.RS_CD IN $$RS_CD --('P-BLI','P-BLI-KW') 
  AND HIST.EFFDT    =
    (SELECT MAX (HIST2.EFFDT)
    FROM $$CCB_SCHEMA.CI_SA_RS_HIST HIST2
    WHERE HIST2.SA_ID = HIST.SA_ID
    )
  ) -- END B_SA
--
SELECT 
EXTRACT(YEAR FROM FT.XFER_TO_GL_DT)
  ||LPAD(EXTRACT(MONTH FROM FT.XFER_TO_GL_DT),2,'0') AS REVENUE_MONTH ,
  FT.XFER_TO_GL_DT                                   AS XFER_TO_GL_DT, 
  TRIM(PN.ENTITY_NAME)                                     AS CUSTOMER, 
  TRIM(BILL.ACCT_ID)                                 AS BILL_ACCOUNT_NBR, 
  TRIM(CCL.DESCR)                                    AS CUSTOMER_CLS,
  TRIM(ACCT.BILL_CYC_CD)                             AS BILL_CYCLE,
  TRIM(SCUSER.FIRST_NAME) ||' ' || TRIM(SCUSER.LAST_NAME)        AS USER_NM, 
  TRIM(CALC.RS_CD)                AS RATE_CD,
  TRIM(RSL.DESCR)                 AS RATE_NM,
  FTGL.AMOUNT               AS CHARGE_AMT,
  SUBSTR(TRIM(FTGL.GL_ACCT),29,6) AS SUB_ACCT ,
  SUBSTR(TRIM(FTGL.GL_ACCT),96,5) AS CUSTOMER_SEGMENT,
  SUBSTR(TRIM(FTGL.GL_ACCT),74,6) AS PRODUCT,
  SUBSTR(TRIM(FTGL.GL_ACCT),7,10) AS DEPT,
  --  --
  (
  SELECT (SQ.BILL_SQ)
  FROM $$CCB_SCHEMA.CI_BSEG_SQ SQ
  WHERE SQ.BSEG_ID = CALC.BSEG_ID
  AND SQ.UOM_CD   IN $$UOM_CD1 --('KWH')
  AND SQI_CD       = $$SQI_CD --'DELIVERED'
  AND TOU_CD       = ' '
  ) AS KWH_USAGE,
  --
  --
  (
  SELECT (SQ.BILL_SQ)
  FROM $$CCB_SCHEMA.CI_BSEG_SQ SQ
  WHERE SQ.BSEG_ID = CALC.BSEG_ID
  AND SQ.UOM_CD   IN $$UOM_CD2 --('KW')
  AND SQI_CD       = $$SQI_CD --'DELIVERED'
  AND TOU_CD       = ' '
  ) AS KW_USAGE,
  -- DEBUG
  TRIM(FT.FT_ID) AS FT_ID,
  TRIM(FT.FT_TYPE_FLG) AS FT_TYPE_FLG,
  FTGL.GL_SEQ_NBR AS GL_SEQ_NBR,
  TRIM(BSEG.BSEG_STAT_FLG) as BSEG_STAT_FLG ,
TRIM(FT.CIS_DIVISION) AS COMPANY_NM,
FT.FREEZE_USER_ID as USER_ID,
PN.PER_ID,
TRIM(CCL.CUST_CL_CD) as CL_CD 
  --
FROM B_SA
INNER JOIN $$CCB_SCHEMA.CI_FT FT
ON FT.SA_ID = B_SA.SA_ID
INNER JOIN $$CCB_SCHEMA.CI_BILL BILL -- BILLS COMPLETED W/I PERIOD
ON BILL.BILL_ID = FT.PARENT_ID
  --  --  --
INNER JOIN $$CCB_SCHEMA.CI_BSEG BSEG
ON BSEG.BILL_ID = BILL.BILL_ID
  --  --  --
INNER JOIN $$CCB_SCHEMA.CI_BSEG_CALC CALC
ON CALC.BSEG_ID = BSEG.BSEG_ID
  --  --  --
INNER JOIN $$CCB_SCHEMA.CI_ACCT ACCT
ON ACCT.ACCT_ID = BILL.ACCT_ID
  --  --
INNER JOIN $$CCB_SCHEMA.CI_CUST_CL_L CCL
ON CCL.CUST_CL_CD   = ACCT.CUST_CL_CD
AND CCL.LANGUAGE_CD = $$LANG_CD --'ENG'
  --
INNER JOIN $$CCB_SCHEMA.CI_ACCT_PER AP
ON AP.ACCT_ID       = BILL.ACCT_ID
AND AP.MAIN_CUST_SW = 'Y'
INNER JOIN $$CCB_SCHEMA.CI_PER_NAME PN
ON PN.PER_ID        = AP.PER_ID
AND PN.PRIM_NAME_SW = 'Y'
  --  --
INNER JOIN $$CCB_SCHEMA.CI_RS_L RSL
ON TRIM(RSL.RS_CD)  = TRIM(CALC.RS_CD)
AND RSL.LANGUAGE_CD = $$LANG_CD --'ENG'
  --  --
LEFT JOIN $$CCB_SCHEMA.SC_USER SCUSER
ON SCUSER.USER_ID = FT.FREEZE_USER_ID
INNER JOIN $$CCB_SCHEMA.CI_FT_GL FTGL
ON FTGL.FT_ID = FT.FT_ID
  --  REVENUE ONLY
AND FTGL.DST_ID IN
  (SELECT DCHAR.DST_ID
  FROM $$CCB_SCHEMA.CI_DST_CODE DST
  INNER JOIN $$CCB_SCHEMA.CI_DST_CD_CHAR DCHAR
  ON DCHAR.DST_ID        = DST.DST_ID
  AND DCHAR.CHAR_TYPE_CD = $$CHAR_TYPE_CD --'GL_ACCT'
  AND DCHAR.CHAR_VAL     = $$CHAR_VAL --'R'
  WHERE DST.CIS_DIVISION = $$COMPANY_PC --'PECO'
  )
  --  --
--WHERE FT.XFER_TO_GL_DT > TO_DATE(:START_DT,'DD-MON-YYYY') 
AND FT.GL_DISTRIB_STATUS = $$GL_D --'D'
AND 
NVL(FT.GG_TCT,TO_DATE('01/01/1900', 'MM/DD/YYYY'))
BETWEEN (
          SELECT DATA_EFF_START_DT_TM
          FROM $$DAP_SCHEMA.TP_TRANSFORMATION_CONTROL B 
          WHERE B.SESSION_NM =  $$SESSION_NAME AND RUN_STATUS='I'
          AND B.SESSION_RUN_START_DT_TM =
                                    (SELECT MAX(SESSION_RUN_START_DT_TM)
                                    FROM  $$DAP_SCHEMA.TP_TRANSFORMATION_CONTROL  
                                     WHERE SESSION_NM =  $$SESSION_NAME AND RUN_STATUS='I')
       )
	 and 
	  (
          SELECT DATA_EFF_END_DT_TM
          FROM $$DAP_SCHEMA.TP_TRANSFORMATION_CONTROL B 
          WHERE B.SESSION_NM =  $$SESSION_NAME AND RUN_STATUS='I'
          AND B.SESSION_RUN_START_DT_TM =
                                    (SELECT MAX(SESSION_RUN_START_DT_TM)
                                    FROM  $$DAP_SCHEMA.TP_TRANSFORMATION_CONTROL  
									 WHERE SESSION_NM =  $$SESSION_NAME AND RUN_STATUS='I')
       )
order by FT_ID,GL_SEQ_NBR